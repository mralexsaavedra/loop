#!/usr/bin/env node
/* Writes services/health-ingest/src/food-calc.js, the ingest service's food log formula, from
 * lib/nutrition/foodlog.mjs (its SERVER descriptor, emitted by lib/build/esm-module.mjs). The service is
 * built from its own directory (its Dockerfile copies only src/ and sql/), so it cannot import lib/ at
 * runtime: it gets a GENERATED copy instead of a hand port. A change is made in the lib first, then
 * `npm run gen:food-calc`; scripts/gen-food-calc.test.mjs fails while the committed file differs.
 * Deterministic (no timestamps). `--check` writes nothing and exits 1 on drift. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SERVER } from '../lib/nutrition/foodlog.mjs';
import { esmModule } from '../lib/build/esm-module.mjs';

export const FOOD_CALC_PATH = fileURLToPath(new URL('../services/health-ingest/src/food-calc.js', import.meta.url));
export const FOOD_CALC_HEADER =
  'GENERATED by scripts/gen-food-calc.mjs from lib/nutrition/foodlog.mjs — do not edit; run `npm run gen:food-calc`';

const HEADER = `${FOOD_CALC_HEADER}.

The food log's macro formula and shared input limits, server side. lib/nutrition/foodlog.mjs is
AUTHORITATIVE: these are its own values and function source (SERVER descriptor), because this service
is built from its own directory (see the Dockerfile) and cannot import lib/. The repo's root suite
checks this file is current (scripts/gen-food-calc.test.mjs) and runs it against the lib over
FOODLOG_CASES / SUMMARY_CASES (lib/nutrition/foodlog.test.mjs).

Nothing is converted between g and ml, a serving exists only when the product states its size, a
recipe with a missing product has no macros, and a log entry stores its rounded SNAPSHOT (kcal
whole, macros 1 decimal) so a later product edit never rewrites history. Pure: no I/O.`;

/** The file's full source, as it must be committed. */
export function foodCalcSource() {
  return esmModule(HEADER, SERVER);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = foodCalcSource();
  const current = (() => {
    try {
      return readFileSync(FOOD_CALC_PATH, 'utf8');
    } catch {
      return null;
    }
  })();
  if (process.argv.includes('--check')) {
    if (current !== src) {
      console.error('services/health-ingest/src/food-calc.js is out of date: run `npm run gen:food-calc`');
      process.exit(1);
    }
    console.log('food-calc.js is current');
  } else if (current === src) {
    console.log('food-calc.js unchanged');
  } else {
    writeFileSync(FOOD_CALC_PATH, src);
    console.log('wrote services/health-ingest/src/food-calc.js');
  }
}
