#!/usr/bin/env node
/* Writes services/loop-ingest/src/profile-rules.js, the ingest service's onboarding-profile vocabularies and
 * bounds (PUT /food/profile), from lib/profile/onboarding.mjs (its SERVER descriptor, emitted by
 * lib/build/esm-module.mjs). The service is built from its own directory (its Dockerfile copies only src/ and
 * sql/), so it cannot import lib/ at runtime: it gets a GENERATED copy instead of a hand copy. A change is made
 * in the lib first, then `npm run gen:profile-rules`; scripts/gen-profile-rules.test.mjs fails while the
 * committed file differs. Deterministic (no timestamps). `--check` writes nothing and exits 1 on drift;
 * `--help` prints the usage; an unknown flag exits 2 before anything is written. */
import { fileURLToPath } from 'node:url';
import { SERVER } from '../lib/profile/onboarding.mjs';
import { esmModule } from '../lib/build/esm-module.mjs';
import { writeGenerated, generatorUsage, GENERATOR_OPTIONS } from './lib/generated.mjs';
import { runCli } from './lib/sync-common.mjs';
import { isMain } from './lib/is-main.mjs';

export const PROFILE_RULES_PATH = fileURLToPath(new URL('../services/loop-ingest/src/profile-rules.js', import.meta.url));
export const PROFILE_RULES_HEADER =
  'GENERATED by scripts/gen-profile-rules.mjs from lib/profile/onboarding.mjs — do not edit; run `npm run gen:profile-rules`';

const HEADER = `${PROFILE_RULES_HEADER}.

The onboarding profile's vocabularies (sex, activity level, sports, day types) and inclusive [min, max]
bounds (age, height, weight, sport minutes and sessions per week), server side. lib/nutrition/energy.mjs
and lib/nutrition/targets.mjs are AUTHORITATIVE: these are their own values (the SERVER descriptor of
lib/profile/onboarding.mjs), because this service is built from its own directory (see the Dockerfile) and
cannot import lib/. The repo's root suite checks this file is current (scripts/gen-profile-rules.test.mjs).`;

/** The file's full source, as it must be committed. */
export function profileRulesSource() {
  return esmModule(HEADER, SERVER);
}

if (isMain(import.meta.url)) {
  runCli(({ check }) => writeGenerated(PROFILE_RULES_PATH, profileRulesSource(), { label: 'services/loop-ingest/src/profile-rules.js', script: 'gen:profile-rules', check: !!check }),
    { usage: generatorUsage('gen:profile-rules', 'services/loop-ingest/src/profile-rules.js'), options: GENERATOR_OPTIONS });
}
