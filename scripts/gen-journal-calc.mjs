#!/usr/bin/env node
/* Writes services/health-ingest/src/journal-calc.js, the ingest service's journal behaviours and limits,
 * from lib/journal/journal.mjs (its SERVER descriptor, emitted by lib/build/esm-module.mjs). The service
 * is built from its own directory (its Dockerfile copies only src/ and sql/), so it cannot import lib/ at
 * runtime: it gets a GENERATED copy instead of a hand copy. A change is made in the lib first, then
 * `npm run gen:journal-calc`; scripts/gen-journal-calc.test.mjs fails while the committed file differs.
 * Deterministic (no timestamps). `--check` writes nothing and exits 1 on drift. */
import { fileURLToPath } from 'node:url';
import { SERVER } from '../lib/journal/journal.mjs';
import { esmModule } from '../lib/build/esm-module.mjs';
import { writeGenerated } from './lib/generated.mjs';
import { isMain } from './lib/is-main.mjs';

export const JOURNAL_CALC_PATH = fileURLToPath(new URL('../services/health-ingest/src/journal-calc.js', import.meta.url));
export const JOURNAL_CALC_HEADER =
  'GENERATED by scripts/gen-journal-calc.mjs from lib/journal/journal.mjs — do not edit; run `npm run gen:journal-calc`';

const HEADER = `${JOURNAL_CALC_HEADER}.

The journal's behaviour groups, behaviours and input limits, server side. lib/journal/journal.mjs is
AUTHORITATIVE: these are its own values (SERVER descriptor), because this service is built from its own
directory (see the Dockerfile) and cannot import lib/. The repo's root suite checks this file is
current (scripts/gen-journal-calc.test.mjs). A behaviour key is stored history: renaming one orphans
its answers.`;

/** The file's full source, as it must be committed. */
export function journalCalcSource() {
  return esmModule(HEADER, SERVER);
}

if (isMain(import.meta.url)) {
  process.exitCode = writeGenerated(JOURNAL_CALC_PATH, journalCalcSource(), {
    label: 'services/health-ingest/src/journal-calc.js',
    script: 'gen:journal-calc',
    check: process.argv.includes('--check'),
  });
}
